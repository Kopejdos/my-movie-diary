/** Vrátí text podle klíče a dosadí parametry: format("movieCount", 12) → "12 movies". */
export function format(key, ...args) {
    const template = TEXTS[key] ?? `???${key}???`;
    return template.replace(/\{(\d+)\}/g, (_, index) => String(args[Number(index)] ?? ""));
}
